#!/usr/bin/env python3
"""Generate firmware/src/instrument_bank_data.inc from assets/presets/bank.json.

The tables hold the spec's 0-127 values verbatim. Modulation the prose calls
for (an LFO, or a filter/pitch envelope) is added from EXTRAS below."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ["ANALOG VCF", "PHASE DIST", "FM BASS", "FM KEYS", "FM PAD", "WAVE TERRAIN",
          "STRING MACH", "CHIPTUNE", "VIRTUAL AN", "WAVESHAPE", "FM", "GRAIN",
          "HARMONIC", "WAVETABLE", "CHORD", "SPEECH", "SWARM", "NOISE", "PARTICLE",
          "STRING", "MODAL", "KICK", "SNARE", "HI HAT"]
# BR_TARGET_* ids: PITCH 1, TIMBRE 2, COLOR 3, FILTER 4.
LFO = {  # preset: (target, rate, depth)
    1: (2, 2, 4),       # REESE: 0.344 Hz (displayed 0.34), 3% timbre depth
    5: (4, 70, 90),     # WOBBLE: filter (the LFO is free-running, not tempo-synced)
    18: (4, 15, 40),    # DEEP CHORD
    28: (3, 20, 45),    # GLASS PAD: morph
    58: (4, 10, 40),    # WIND
}
ENV = {  # preset: (target, amount, decay)
    3: (4, 60, 30),     # ACID LINE: filter envelope
    40: (1, -40, 40),   # HOOVER: pitch drops in
    55: (4, 80, 80),    # NOISE SWP: filter envelope
    56: (1, -90, 20),   # ZAP: pitch falls
}
AUX = {1: 8}            # REESE: 6% AUX; other sounds retain their midpoint

def main():
    spec = ROOT / 'assets/presets/bank.json'
    rows = []
    for item in json.loads(spec.read_text()):
        n, name, engine = item['number'], item['name'], item['engine']
        h, t, mo = item['sound']
        f, q = item['filter']
        a, d, s, r = item['envelope']
        dly, rev = item['effects']
        assert len(name) <= 10, name
        # Spec engine names: "FM" bank entries are Plaits FM; strip nothing else.
        model = MODELS.index(engine)
        lfo = LFO.get(n, (0, 32, 0))
        env = ENV.get(n, (0, 0, 64))
        rows.append((n, name, model, h, t, mo, f, q, a, d, s, r, dly, rev, lfo, env))
    assert [r[0] for r in rows] == list(range(1, 65)), len(rows)
    out = ['/* Generated by tools/gen_bank.py from assets/presets/bank.json. */']
    for n, name, model, h, t, mo, f, q, a, d, s, r, dly, rev, lfo, env in rows:
        out.append('    {"%s", %d, %d,%d,%d, %d,%d, %d,%d,%d,%d, %d,%d, %d,%d,%d, %d,%d,%d, %d},'
                   % (name, model, h, t, mo, f, q, a, d, s, r, dly, rev,
                      lfo[0], lfo[1], lfo[2], env[0], env[1], env[2], AUX.get(n, 64)))
    dest = ROOT / 'firmware/src/instrument_bank_data.inc'
    dest.write_text('\n'.join(out) + '\n')
    print('wrote', dest, len(rows), 'presets')

if __name__ == '__main__':
    sys.exit(main())
