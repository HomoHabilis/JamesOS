#!/usr/bin/env python3
"""Generate firmware/src/instrument_bank_data.inc from assets/presets/bank.json.

The bank specifies model, sound, effects and modulation values explicitly."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ["ANALOG VCF", "PHASE DIST", "FM BASS", "FM KEYS", "FM PAD", "WAVE TERRAIN",
          "STRING MACH", "CHIPTUNE", "VIRTUAL AN", "WAVESHAPE", "FM", "FORMANT",
          "HARMONIC", "WAVETABLE", "CHORD", "SPEECH", "SWARM", "NOISE", "PARTICLE",
          "STRING", "MODAL", "KICK", "SNARE", "HI HAT"]
def main():
    spec = ROOT / 'assets/presets/bank.json'
    rows = []
    for item in json.loads(spec.read_text()):
        n, name, engine = item['number'], item['name'], item['engine']
        h, t, mo = item['sound']
        f, q = item['filter']
        a, d, s, r = item['envelope']
        dly, rev, drive = item['effects']
        assert 0 < len(name) <= 10 and all(c.isupper() or c.isdigit() or c == " " for c in name), name
        model = MODELS.index(engine)
        lfo = item['lfo']
        env = item['mod_envelope']
        aux = item['aux']
        voice_mode = {'MONO': 1, 'POLY': 2}[item['voice_mode']]
        values = [h, t, mo, f, q, a, d, s, r, dly, rev, drive, *lfo, env[0], env[2], aux]
        assert all(0 <= v <= 127 for v in values), (n, values)
        assert -127 <= env[1] <= 127, (n, env)
        assert lfo[0] in (0, 1, 2, 3, 4) and env[0] in (0, 1, 2, 3, 4), n
        rows.append((n, name, model, h, t, mo, f, q, a, d, s, r, dly, rev, drive, lfo, env, aux, voice_mode))
    assert [r[0] for r in rows] == list(range(1, 129)), len(rows)
    assert len({r[1] for r in rows}) == len(rows), "duplicate sound name"
    out = ['/* Generated by tools/gen_bank.py from assets/presets/bank.json. */']
    for n, name, model, h, t, mo, f, q, a, d, s, r, dly, rev, drive, lfo, env, aux, voice_mode in rows:
        out.append('    {"%s", %d, %d,%d,%d, %d,%d, %d,%d,%d,%d, %d,%d,%d, %d,%d,%d, %d,%d,%d, %d, %d},'
                   % (name, model, h, t, mo, f, q, a, d, s, r, dly, rev, drive,
                      lfo[0], lfo[1], lfo[2], env[0], env[1], env[2], aux, voice_mode))
    dest = ROOT / 'firmware/src/instrument_bank_data.inc'
    dest.write_text('\n'.join(out) + '\n')
    print('wrote', dest, len(rows), 'presets')

if __name__ == '__main__':
    sys.exit(main())
