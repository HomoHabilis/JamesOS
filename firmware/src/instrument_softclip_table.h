static inline __attribute__((always_inline)) int32_t br_fx_softclip_table_bounded(int32_t x)
{
    uint32_t m = x < 0 ? 0u - (uint32_t)x : (uint32_t)x;
    uint32_t index = m >> 8;
    uint32_t a = br_fx_softclip_curve[index];
    uint32_t b = br_fx_softclip_curve[index + 1u];
    int32_t result = (int32_t)(a + (((b - a) * (m & 255u) + 128u) >> 8));
    return x < 0 ? -result : result;
}
