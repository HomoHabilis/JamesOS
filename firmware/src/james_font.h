/* Missing specimen symbols use the former UI's pixel forms. Rows are returned
 * right-aligned; callers draw all eight rows and advance width + one pixel. */
static uint32_t james_font_width(uint8_t ch)
{
    if (ch >= 32u && ch <= 126u && (specimen_glyphs[ch - 32u].width || ch == ' '))
        return ch == ' ' ? 3u : specimen_glyphs[ch - 32u].width;
    switch (ch) {
    case '#': case '/': case '>': case '<': case '_': case '=': return 5u;
    default: return 5u; /* visible missing-character box */
    }
}
static uint8_t james_font_row(uint8_t ch, uint32_t row)
{
    uint32_t w = james_font_width(ch);
    if (row >= 8u || ch == ' ') return 0u;
    if (ch >= 32u && ch <= 126u && (specimen_glyphs[ch - 32u].width || ch == ' '))
        return (uint8_t)(specimen_glyphs[ch - 32u].rows[row] >> (8u - w));
    switch (ch) {
    case '/': { static const uint8_t r[8] = {1,1,2,4,8,16,16,0}; return r[row]; }
    case '#': return row == 2u || row == 4u ? 31u : row >= 1u && row <= 5u ? 10u : 0u;
    case '>': return row == 1u || row == 5u ? 8u : row == 2u || row == 4u ? 4u : row == 3u ? 2u : 0u;
    case '<': return row == 1u || row == 5u ? 2u : row == 2u || row == 4u ? 4u : row == 3u ? 8u : 0u;
    case '_': return row == 6u ? 31u : 0u;
    case '=': return row == 2u || row == 4u ? 14u : 0u;
    default: return row == 0u || row == 6u ? 31u : row < 6u ? 17u : 0u;
    }
}
